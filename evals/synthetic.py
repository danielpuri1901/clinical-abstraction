def correction_doc(template: str, patient: Patient, visit: Visit, when: tuple) -> tuple:
    arrival = visit.present[0][0] != visit.start
    name, new, old = (
        ("patient_arrival", visit.present[0][0], visit.start)
        if arrival
        else ("patient_departure", visit.present[0][1], visit.end)
    )
    word = (
        {"A": "arrival", "B": "sign-in time", "C": "arrival"}[template]
        if arrival
        else {"A": "departure", "B": "sign-out time", "C": "departure"}[template]
    )
    lines = header_lines(template, patient, "correction")
    cited_lines = append_lines(
        lines,
        field_line(template, "Applies to", f"encounter {visit.id}, service date {date_text(template, visit.day)}"),
        field_line(
            template,
            "Correction",
            f"patient {word} for {visit.id} is {clock_time(template, new)}, "
            f"replacing the original value of {clock_time(template, old)}",
        ),
    )
    append_lines(lines, "The front desk log was reviewed; no additional clinical service was provided in making this correction.")
    append_lines(lines, signature_line(template, patient.facilitator, *when))
    correction = Correction(
        encounter_id=visit.id,
        service_date=visit.day.isoformat(),
        field=name,
        corrected_value=colon_time(new),
        replaced_value=colon_time(old),
        lines=cited_lines,
    )
    return "correction", lines, extraction(patient, "correction", when, corrections=[correction])


