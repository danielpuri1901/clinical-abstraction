def schedule_visits(
    draw: random.Random, template: str, number: str, start: date, hazards: list[str]
) -> tuple[list[Visit], dict[str, Visit]]:
    """Two to five encounters per week, at most one per half day and one of each kind per day, so none overlap."""
    slots = []
    for week in range(4):
        monday = start + timedelta(weeks=week)
        for weekday, half in sorted(draw.sample([(d, h) for d in range(5) for h in range(2)], draw.randint(2, 5))):
            on = monday + timedelta(days=weekday)
            kinds = [kind for kind in KIND_WEIGHTS if not any(slot[0] == on and slot[2] == kind for slot in slots)]
            slots.append([on, half, draw.choices(kinds, [KIND_WEIGHTS[kind] for kind in kinds])[0]])
    roles = {}
    for name in ("correction", "conflicting_notes", "draft_and_charge", "clinic_cancellation"):
        if name in hazards:
            kind = INDIVIDUAL if name == "conflicting_notes" else GROUP
            free = [i for i in range(len(slots)) if i not in roles]
            fits = [
                i
                for i in free
                if not any(j != i and slots[j][0] == slots[i][0] and slots[j][2] == kind for j in range(len(slots)))
            ]
            i = draw.choice(fits or free)
            roles[i] = name
            if name != "draft_and_charge" or slots[i][2] not in (INDIVIDUAL, GROUP):
                slots[i][2] = kind
    visits, special = [], {}
    for i, (on, half, kind) in enumerate(slots):
        if kind == GROUP:
            begin = 600 if half == 0 else 780
            finish = begin + 90
        else:
            begin = 540 if half == 0 else draw.choice([840, 900, 960])
            finish = begin + draw.choice(DURATIONS[kind])
        visit = Visit(
            f"SY-{'V' if template == 'B' else 'E'}{number}{i + 1:02d}",
            on,
            kind,
            begin,
            finish,
            signed=finish + draw.choice([20, 35, 50, 75]),
        )
        role = roles.get(i)
        if role:
            special[role] = visit
        if role == "draft_and_charge":
            visit.status = "no_show"
        elif role == "clinic_cancellation":
            visit.status = "cancelled_by_clinic"
        elif kind == GROUP:
            pause = begin + draw.choice([40, 45])
            visit.cuts = [(pause, pause + draw.choice([10, 15, 20]), "break")]
            arrive, leave = begin, finish
            if role == "correction" and draw.random() < 0.5:
                arrive += draw.choice([10, 15, 20])
            elif role == "correction":
                leave -= draw.choice([15, 20, 30])
            elif draw.random() < LATE_ARRIVAL:
                arrive += draw.choice([10, 15, 20, 30])
                visit.status = "attended_partial"
            visit.present = [(arrive, leave)]
        elif role == "conflicting_notes":
            visit.present = [(begin + draw.choice([10, 15]), finish)]  # one note will carry the scheduled start instead
        elif kind == INDIVIDUAL and draw.random() < VIDEO:
            visit.video, visit.present = True, [(begin, finish)]
            if draw.random() < DISCONNECT:
                drop = begin + draw.choice([15, 20, 25])
                back = drop + draw.choice([5, 10])
                visit.present, visit.cuts = [(begin, drop), (back, finish)], [(drop, back, "disconnect")]
        elif kind == FAMILY and draw.random() < PARTNER_ONLY:
            joined = begin + draw.choice([10, 15])
            visit.present, visit.cuts = [(joined, finish)], [(begin, joined, "patient_not_present")]
        elif kind == COLLATERAL:
            visit.status = "patient_absent"
        else:
            visit.present = [(begin, finish)]
        visits.append(visit)
    return visits, special


def straddle_goal(draw: random.Random, visits: list[Visit], special: dict[str, Visit], plans: list[dict]) -> None:
    """Move an unsettled conflict to a session whose week can straddle the minute goal, and time it to do so.

    The rest of the week stays as drawn. The session lasts 30 to 90 minutes. The co-therapist's note, which is the truth,
    starts 5 to 30 minutes late and keeps at least 15 minutes of contact, so the week stays below the goal; the other
    note carries the scheduled start, so the week reaches the goal. The host is an in-person individual session, else a
    medication or collateral visit that becomes one. Without such a week the drawn times stay.
    """
    drawn = special["conflicting_notes"]
    taken = {visit.id for name, visit in special.items() if name != "conflicting_notes"}
    late_start, drawn.present = drawn.present, [(drawn.start, drawn.end)]
    sessions, conversions = [], []
    for host in visits:
        session = host.kind == INDIVIDUAL and not host.video
        if host.id in taken or not (session or host.kind in (MEDICATION, COLLATERAL)):
            continue
        if any(visit is not host and visit.day == host.day and visit.kind == INDIVIDUAL for visit in visits):
            continue  # one individual session per day
        monday = host.day - timedelta(days=host.day.weekday())
        week = [visit for visit in visits if visit is not host and counts(visit) and 0 <= (visit.day - monday).days < 7]
        plan = [plan for plan in plans if plan["effective_date"] <= monday.isoformat()][-1]
        need = plan["min_minutes_per_week"] - sum(visit_minutes(visit) for visit in week)
        if len({visit.day for visit in week} | {host.day}) >= plan["min_days_per_week"] and 20 <= need <= 90:
            (sessions if session else conversions).append((host, need))
    if not sessions + conversions:
        drawn.present = late_start
        return
    host, need = draw.choice(sessions or conversions)
    length = draw.choice([minutes for minutes in range(30, 95, 5) if need <= minutes <= need + 25])
    contact = draw.choice([minutes for minutes in range(15, 90, 5) if length - 30 <= minutes <= min(need, length) - 5])
    host.kind, host.status, host.cuts = INDIVIDUAL, "attended", []
    host.signed += host.start + length - host.end
    host.end = host.start + length
    host.present = [(host.end - contact, host.end)]
    special["conflicting_notes"] = host


def gold_values(
    mrn: str,
    start: date,
    end: date,
    visits: list[Visit],
    plans: list[dict],
    administrations: list[tuple],
    special: dict[str, Visit],
    hazards: list[str],
) -> dict:
    """Expected abstraction values, computed from the truth with this module's own arithmetic."""
    minutes = {}
    for visit in visits:
        if counts(visit):
            value = visit_minutes(visit)
            unsettled = visit is special.get("conflicting_notes") and "addendum" not in hazards
            # An unsettled conflict also keeps the other signed note, which carries the scheduled start.
            minutes[visit.id] = [value, visit.end - visit.start if unsettled else value]
    encounters = {}
    for visit in visits:
        if visit.status in ("no_show", "cancelled_by_clinic"):
            encounters[visit.id] = {"service_date": visit.day.isoformat(), "status": visit.status, "counts_as_therapy": "no"}
            continue
        encounters[visit.id] = {
            "service_date": visit.day.isoformat(),
            "service_type": visit.kind,
            "counts_as_therapy": "yes" if visit.id in minutes else "no",
        }
        if visit.id in minutes:
            encounters[visit.id]["minutes"] = minutes[visit.id]
        if visit.video:
            encounters[visit.id]["modality"] = "video"
    counted = [visit for visit in visits if visit.id in minutes]
    weeks = []
    for week in range(4):
        monday = start + timedelta(weeks=week)
        inside = [visit for visit in counted if monday <= visit.day < monday + timedelta(days=7)]
        days, low, high = (
            len({visit.day for visit in inside}),
            sum(minutes[visit.id][0] for visit in inside),
            sum(minutes[visit.id][1] for visit in inside),
        )
        plan = [plan for plan in plans if plan["effective_date"] <= monday.isoformat()][-1]
        weeks.append(
            {
                "week_start": monday.isoformat(),
                "therapy_days": [days, days],
                "minutes": [low, high],
                "status": goal_status(plan, days, days, low, high),
            }
        )
    by_type = {}
    for visit in counted:
        by_type[visit.kind] = by_type.get(visit.kind, 0) + 1
    pairs = list(pairwise(weeks))
    flags = []
    if "draft_and_charge" in special:
        flags.append(["charge_for_undelivered_service", special["draft_and_charge"].id])
    if "conflicting_notes" in special and "addendum" not in hazards:
        flags.append(["unresolved_minutes_conflict", special["conflicting_notes"].id])
    return {
        "_about": "Generated by evals/synthetic.py from this patient's known truth before any document was rendered. "
        "Minutes are [low, high] patient-present psychotherapy minutes; a range remains only where signed records "
        "disagree and no correction settles it. Used only by tests and evals; the pipeline never reads this file.",
        "mrn": mrn,
        "review_period": [start.isoformat(), end.isoformat()],
        "encounters": encounters,
        "counted_encounters": sorted(minutes),
        "weeks": weeks,
        "totals": {
            "sessions": len(counted),
            "by_service_type": by_type,
            "therapy_days": len({visit.day for visit in counted}),
            "minutes": [sum(low for low, _ in minutes.values()), sum(high for _, high in minutes.values())],
        },
        "assessments": [
            {"instrument": "PHQ-9", "completed_on": on.isoformat(), "total_score": score}
            for _, on, _, score, _ in administrations
        ],
        "required_flags": flags,
        "consecutive_weeks_below_goal": {
            "run_length": 2,
            "established": [
                [first["week_start"], second["week_start"]]
                for first, second in pairs
                if first["status"] == second["status"] == "not_met"
            ],
            "depends_on_unresolved_records": [
                [first["week_start"], second["week_start"]]
                for first, second in pairs
                if {first["status"], second["status"]} <= {"not_met", "cannot_determine"}
                and "cannot_determine" in (first["status"], second["status"])
            ],
        },
    }


def synthesize_patient(seed: int, index: int) -> tuple[dict, list[tuple[str, str, DocumentExtraction]], dict]:
    """Manifest entry, documents as (file name, text, truth extraction), and gold file for one patient."""
    draw = random.Random(seed * 1000 + index)
    number, template = f"{seed % 100:02d}{index:03d}", "ABC"[(seed + index) % 3]
    therapist, cotherapist = draw.sample(THERAPISTS, 2)
    patient = Patient(
        mrn=f"SY-M{number}",
        name=f"{draw.choice(FIRST_NAMES)} {draw.choice(LAST_NAMES)}",
        birth_date=date(draw.randint(1960, 2002), draw.randint(1, 12), draw.randint(1, 28)),
        partner=draw.choice(PARTNER_NAMES),
        therapist=therapist,
        cotherapist=cotherapist,
        facilitator=draw.choice(FACILITATORS),
        prescriber=draw.choice(PRESCRIBERS),
        staff=draw.choice(STAFF),
    )
    start = date(2026, 1, 5) + timedelta(weeks=draw.randrange(8))  # a Monday in January or February 2026
    end = start + timedelta(days=25)  # the Friday of week 4
    hazards = [name for name in RATES if name not in NEEDS and draw.random() < RATES[name]]
    hazards += [name for name, needed in NEEDS.items() if needed in hazards and draw.random() < RATES[name]]
    visits, special = schedule_visits(draw, template, number, start, hazards)

    goals = draw.sample(GOALS, 2)
    changed = start + timedelta(weeks=2)
    plans = [
        {"effective_date": on.isoformat(), "min_days_per_week": days, "min_minutes_per_week": minutes}
        for on, (days, minutes) in zip((start, changed), goals[: 1 + ("plan_change" in hazards)])
    ]
    if "conflicting_notes" in hazards and "addendum" not in hazards:
        straddle_goal(draw, visits, special, plans)
    docs = [plan_doc(template, patient, start, end, goals[0], 480 + draw.randint(0, 50))]
    if "plan_change" in hazards:
        docs.append(plan_update_doc(template, patient, changed, end, goals[1], 470 + draw.randint(0, 40)))
    administrations, score = [], draw.randint(12, 22)
    for n, on in enumerate((start, start + timedelta(days=21 + draw.randint(0, 4))), start=1):
        completed = 480 + draw.randint(0, 40)
        administrations.append((f"SY-Q{number}-{n}", on, completed, score, completed + draw.randint(30, 90)))
        score = max(0, score - draw.randint(2, 8))
    docs += [questionnaire_doc(template, patient, *administration) for administration in administrations]
    if "imported_copy" in hazards:
        form, on, _, score, reviewed = administrations[0]
        received = (on + timedelta(days=draw.randint(8, 18)), 460 + draw.randint(0, 30))
        docs.append(imported_doc(template, patient, form, on, score, reviewed, received))

    if visit := special.get("correction"):
        arrival_fixed = visit.present[0][0] != visit.start
        stated = replace(
            visit, present=[(visit.start, visit.present[0][1])] if arrival_fixed else [(visit.present[0][0], visit.end)]
        )
        docs.append(encounter_doc(template, patient, [(stated, None, "attendance_record")], "attendance_record"))
        docs.append(correction_doc(template, patient, visit, (visit.day + timedelta(days=1), 480 + draw.randint(0, 60))))
        if "late_copy" in hazards:
            received = (visit.day + timedelta(days=draw.randint(4, 7)), 900 + draw.randint(0, 90))
            docs.append(late_copy_doc(template, patient, stated, received))
    if visit := special.get("conflicting_notes"):
        docs.append(
            encounter_doc(
                template, patient, [(replace(visit, present=[(visit.start, visit.end)]), patient.therapist, "clinical_note")]
            )
        )
        docs.append(
            encounter_doc(
                template,
                patient,
                [(replace(visit, signed=visit.signed + draw.choice([25, 45])), patient.cotherapist, "clinical_note")],
                "cotherapist_record",
            )
        )
        if "addendum" in hazards:
            authored = (visit.day + timedelta(days=draw.randint(2, 5)), 600 + draw.randint(0, 60))
            docs.append(addendum_doc(template, patient, visit, authored))
    if visit := special.get("draft_and_charge"):
        docs.append(draft_doc(template, patient, visit, f"CH-{number}{visit.id[-2:]}"))
    if visit := special.get("clinic_cancellation"):
        docs.append(cancellation_doc(template, patient, visit))

    # The rest of the encounters share documents, sized so every patient has 10 to 15 files.
    own_document_ids = {
        special[name].id for name in ("correction", "conflicting_notes", "clinic_cancellation") if name in special
    }
    routine = [visit for visit in visits if visit.id not in own_document_ids]
    fixed = len(docs) + ("duplicate" in hazards)
    target = draw.randint(max(10, fixed + 1), min(15, fixed + len(routine)))
    cuts = sorted(draw.sample(range(1, len(routine)), target - fixed - 1))
    for first, last in zip([0, *cuts], [*cuts, len(routine)]):
        docs.append(
            encounter_doc(
                template,
                patient,
                [
                    (visit, None, "attendance_record" if visit.status == "no_show" else "clinical_note")
                    for visit in routine[first:last]
                ],
            )
        )
    docs.sort(key=lambda doc: max(doc[2].authored_at, doc[2].received_at or ""))  # filing order
    if "duplicate" in hazards:
        docs.append(draw.choice(docs))  # the same bytes filed a second time
    documents = [
        (f"{patient.mrn}_{seq:02d}_{kind}.txt", "\n".join(lines) + "\n", truth)
        for seq, (kind, lines, truth) in enumerate(docs, 1)
    ]

    found = set(hazards)
    if any(cut[2] == "disconnect" for visit in visits for cut in visit.cuts):
        found.add("video_disconnect")
    if any(cut[2] == "patient_not_present" for visit in visits for cut in visit.cuts):
        found.add("partner_only_minutes")
    if template == "C":
        found |= {"day_first_dates", "twelve_hour_times", "bare_times"}
    entry = {
        "mrn": patient.mrn,
        "seed": seed,
        "index": index,
        "template": template,
        "hazards": [h for h in HAZARDS if h in found],
        "documents": len(documents),
        "files": [name for name, _, _ in documents],
    }
    gold = gold_values(patient.mrn, start, end, visits, plans, administrations, special, hazards)
    entry["week_statuses"] = {status: sum(week["status"] == status for week in gold["weeks"]) for status in WEEK_STATUSES}
    return entry, documents, gold


def generate(seed: int, patients: int, out: Path) -> dict:
    """Write out/documents/<MRN>_*.txt, out/gold/<MRN>.json, and out/manifest.json; return the manifest."""
    out = Path(out)
    for folder in ("documents", "gold"):
        (out / folder).mkdir(parents=True, exist_ok=True)
    manifest = {"seed": seed, "hazard_rates": RATES, "week_statuses": dict.fromkeys(WEEK_STATUSES, 0), "patients": []}
    for index in range(1, patients + 1):
        entry, documents, gold = synthesize_patient(seed, index)
        for status, weeks in entry["week_statuses"].items():
            manifest["week_statuses"][status] += weeks
        for name, text, _ in documents:
            (out / "documents" / name).write_text(text, encoding="utf-8")
        (out / "gold" / f"{entry['mrn']}.json").write_text(json.dumps(gold, indent=2) + "\n", encoding="utf-8")
        manifest["patients"].append(entry)
    (out / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    return manifest


def truth_extractions(entry: dict) -> list:
    """The truth for one manifest entry as reconcile.Doc objects, one per distinct document text."""
    docs, seen = [], set()
    for name, text, truth in synthesize_patient(entry["seed"], entry["index"])[1]:
        sha = hashlib.sha256(text.encode()).hexdigest()
        if sha not in seen:  # the pipeline registers a byte-identical duplicate once
            seen.add(sha)
            docs.append(
                Doc(
                    doc_id=name.removesuffix(".txt"),
                    sha=sha,
                    text=text,
                    extraction=truth,
                    authored_at=truth.authored_at,
                    received_at=truth.received_at,
                )
            )
    return docs


