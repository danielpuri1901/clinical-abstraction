# Gold arithmetic ---------------------------------------------------------------------------------------------------


def minutes_present(present: list[tuple[int, int]], excluded: list[tuple[int, int]]) -> int:
    """Patient-present minutes: the present intervals minus the part of each excluded interval inside them."""
    return sum(
        end - start - sum(max(0, min(end, cut_end) - max(start, cut_start)) for cut_start, cut_end in excluded)
        for start, end in present
    )


def goal_status(plan: dict, days_low: int, days_high: int, minutes_low: int, minutes_high: int) -> str:
    """Met only when the low bounds meet the goal, not met when even the high bounds miss it, else open."""
    if days_low >= plan["min_days_per_week"] and minutes_low >= plan["min_minutes_per_week"]:
        return "met"
    if days_high < plan["min_days_per_week"] or minutes_high < plan["min_minutes_per_week"]:
        return "not_met"
    return "cannot_determine"


def counts(visit: Visit) -> bool:
    """A delivered psychotherapy session counts toward the plan goal."""
    return visit.kind in THERAPY and visit.status in ("attended", "attended_partial")


def visit_minutes(visit: Visit) -> int:
    return minutes_present(visit.present, [cut[:2] for cut in visit.cuts])


# Formats per template ----------------------------------------------------------------------------------------------


def colon_time(minutes: int) -> str:
    return f"{minutes // 60:02d}:{minutes % 60:02d}"


def bare_time(minutes: int) -> str:
    return colon_time(minutes).replace(":", "")


def clock_time(template: str, minutes: int) -> str:
    """Templates A and B write 24-hour times; template C writes 12-hour times."""
    if template != "C":
        return colon_time(minutes)
    hour, minute = divmod(minutes, 60)
    return f"{(hour - 1) % 12 + 1}:{minute:02d} {'AM' if hour < 12 else 'PM'}"


def time_span(template: str, start: int, end: int) -> str:
    return {
        "A": f"{colon_time(start)}–{colon_time(end)}",
        "B": f"{colon_time(start)} to {colon_time(end)}",
        "C": f"{bare_time(start)} to {bare_time(end)}",
    }[template]


def date_text(template: str, on: date) -> str:
    month = MONTHS[on.month - 1]
    return {"A": f"{month} {on.day}, {on.year}", "B": f"{on:%m/%d/%Y}", "C": f"{on.day} {month} {on.year}"}[template]


def date_time_text(template: str, on: date, minutes: int) -> str:
    return {
        "A": f"{date_text(template, on)}, {colon_time(minutes)}",
        "B": f"{date_text(template, on)} {colon_time(minutes)}",
        "C": f"{date_text(template, on)} {bare_time(minutes)}",
    }[template]


def signature_line(template: str, signer: str, on: date, minutes: int) -> str:
    return {
        "A": f"Electronically signed: {signer} | {date_time_text(template, on, minutes)}",
        "B": f"Signed by {signer} on {date_time_text(template, on, minutes)}.",
        "C": f"Signed | {signer} | {date_time_text(template, on, minutes)}",
    }[template]


def field_line(template: str, label: str, value: str) -> str:
    return f"{label} | {value}" if template == "C" else f"{label}: {value}"


def iso_date_time(on: date, minutes: int) -> str:
    return f"{on.isoformat()}T{colon_time(minutes)}"


def append_lines(lines: list[str], *texts: str) -> list[int]:
    """Append lines and return their 1-based numbers, the citations for whatever they state."""
    lines.extend(texts)
    return list(range(len(lines) - len(texts) + 1, len(lines) + 1))


def header_lines(template: str, patient: Patient, kind: str) -> list[str]:
    title = TITLES[kind]["ABC".index(template)]
    if template == "A":
        return [
            SYNTHETIC_BANNER,
            ORGANIZATION[template],
            title,
            f"Patient: {patient.name} | DOB: {patient.birth_date.isoformat()} | MRN: {patient.mrn}",
            "",
        ]
    if template == "B":
        return [
            SYNTHETIC_BANNER,
            f"{ORGANIZATION[template]} - {title.upper()}",
            f"Client: {patient.name} | DOB {patient.birth_date.isoformat()} | Record #: {patient.mrn}",
            "",
        ]
    return [
        SYNTHETIC_BANNER,
        f"{ORGANIZATION[template]} | {title}",
        f"Client | {patient.name} | Born {date_text(template, patient.birth_date)} | Medical record number: {patient.mrn}",
        "",
    ]


